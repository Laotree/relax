#[test]
fn constructor_fn_past_u8_glue_kind_keeps_its_variant() {
    let cases: [(fn(u32) -> Wide, u16); 5] = [
        (Wide::V0, 0),
        (Wide::V239, 239),
        (Wide::V240, 240),
        (Wide::V246, 246),
        (Wide::V255, 255),
    ];
    for (ctor, index) in cases {
        let v = apply(ctor, 7);
        assert_eq!(tag(&v), index, "variant {index} constructor built {v:?}");
        assert_eq!(payload(&v), 7, "variant {index} payload");
        drop(v);
    }
}
