#!/usr/bin/env python3
"""Generates ../src/nfc_tables.rs: the Unicode tables behind identifier NFC normalization
(rustc_parse lexer `nfc_normalize`, UAX #15): canonical decompositions, canonical combining
classes and primary composites. Run: python3 nfc_tables.py > ../src/nfc_tables.rs
The Unicode version is the running Python's `unicodedata.unidata_version`."""
import sys
import unicodedata as ud

HANGUL_S, HANGUL_S_END = 0xAC00, 0xAC00 + 11172

decomp = []   # (char, [code points]) single-step canonical mappings
for c in range(0x110000):
    if 0xD800 <= c < 0xE000 or HANGUL_S <= c < HANGUL_S_END:
        continue
    d = ud.decomposition(chr(c))
    if not d or d.startswith('<'):
        continue
    decomp.append((c, [int(x, 16) for x in d.split()]))

ccc = []      # (first, last, class) runs
run = None
for c in range(0x110000):
    k = ud.combining(chr(c))
    if k and run and run[2] == k and run[1] + 1 == c:
        run[1] = c
    elif k:
        if run:
            ccc.append(tuple(run))
        run = [c, c, k]
if run:
    ccc.append(tuple(run))

comp = []     # (first, second, composite): the pairs NFC recomposes
for c, d in decomp:
    if len(d) == 2 and ud.normalize('NFC', chr(d[0]) + chr(d[1])) == chr(c):
        comp.append((d[0], d[1], c))
comp.sort()

out = sys.stdout
out.write("//! Generated by gen/nfc_tables.py from Unicode %s: do not edit.\n\n" % ud.unidata_version)
out.write("/// (code point, its single-step canonical decomposition), sorted by code point.\n")
out.write("pub static DECOMPOSITION: &[(u32, &[u32])] = &[\n")
for c, d in decomp:
    out.write("    (0x%X, &[%s]),\n" % (c, ", ".join("0x%X" % x for x in d)))
out.write("];\n\n/// (first, last, canonical combining class) runs of non-starters, sorted.\n")
out.write("pub static COMBINING_CLASS: &[(u32, u32, u8)] = &[\n")
for a, b, k in ccc:
    out.write("    (0x%X, 0x%X, %d),\n" % (a, b, k))
out.write("];\n\n/// (first, second, composite) primary composites, sorted by (first, second).\n")
out.write("pub static COMPOSITION: &[(u32, u32, u32)] = &[\n")
for a, b, c in comp:
    out.write("    (0x%X, 0x%X, 0x%X),\n" % (a, b, c))
out.write("];\n")
